function generateExtendedRestaurants(): Restaurant[] {
  const list: Restaurant[] = RESTAURANT_DEFINITIONS.map(r => ({
    ...r,
    menuItemIds: []
  }));
  let idCounter = 16;

  for (let i = 0; i < RESTAURANT_NAME_PREFIXES.length; i++) {
    for (let j = 0; j < 3; j++) {
      if (list.length >= 106) break;
      const prefix = RESTAURANT_NAME_PREFIXES[i];
      const suffix = RESTAURANT_NAME_SUFFIXES[(i * 3 + j) % RESTAURANT_NAME_SUFFIXES.length];
      const name = `${prefix} ${suffix}`;
      const cuisines = CUISINE_POOL[(i + j) % CUISINE_POOL.length];
      const rating = Number((4.1 + ((i * 7 + j * 13) % 9) * 0.1).toFixed(1));
      const ratingCount = 200 + ((i * 113 + j * 97) % 3500);
      const deliveryTimeMin = 15 + ((i + j) % 4) * 5;
      const deliveryTimeMax = deliveryTimeMin + 10;
      const distanceKm = Number((1.1 + ((i * 3 + j) % 35) * 0.1).toFixed(1));
      const costForTwo = 350 + ((i * 35 + j * 50) % 650);
      const isPureVeg = (i + j) % 5 === 0;
      const hasOffers = (i + j) % 2 === 0;
      const city = CITIES[(i + j) % CITIES.length];
      const street = STREETS[(i * 2 + j) % STREETS.length];
      const img = RESTAURANT_IMAGES[(i + j) % RESTAURANT_IMAGES.length];

      list.push({
        id: `rest-${idCounter}`,
        name,
        slug: name.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
        cuisines,
        rating,
        ratingCount,
        deliveryTimeMin,
        deliveryTimeMax,
        distanceKm,
        costForTwo,
        image: img,
        coverImage: img,
        logo: isPureVeg ? '🌱' : '⭐',
        address: `${10 + idCounter}, ${street}`,
        city,
        isPureVeg,
        hasOffers,
        offerText: hasOffers ? `${10 + ((idCounter * 5) % 40)}% OFF on all orders` : undefined,
        isBestseller: rating >= 4.7,
        isOpen: true,
        openingHours: '10:30 AM - 11:30 PM',
        freeDeliveryOver: 299,
        featuredDish: `Signature Chef's Special ${cuisines[0]}`,
        description: `Experience handcrafted, freshly prepared ${cuisines.join(' & ')} crafted with organic ingredients and authentic secret spices.`,
        menuItemIds: []
      });
      idCounter++;
    }
  }

  return list;
}

